def house(variant):
    walls, roofc, door = [("brick", "shingle", TEAL), ("plaster", "shingle", "8E3B6B"), ("brick", "shingle", "C7362B")][variant]
    m = Model(f"house_{variant}")
    w, h, d = 3.2, 2.4, 2.4
    m.add(box((-w / 2, 0, -d / 2), (w / 2, h, d / 2), bevel=0.02), tex(walls), uv_scale=1.0)
    m.add(prism([(-w / 2, h), (w / 2, h), (0, h + 1.2)], -d / 2 + 0.02, d / 2 - 0.02), tex(walls), uv_scale=1.0)   # gables
    # roof: two sloped slabs, shingles textured along the slope
    pitch = math.degrees(math.atan2(1.4, w / 2 + 0.2))
    slope = math.hypot(w / 2 + 0.2, 1.4) + 0.05
    for s in (-1, 1):
        # built with the slope along local z so the shingle rows (texture v) run along the ridge
        slab_ = box((-d / 2 - 0.25, -0.06, -slope), (d / 2 + 0.25, 0.0, 0.0), bevel=0.01)
        t = Matrix.Translation((0, h + 1.4, 0)) @ Matrix.Rotation(math.radians(-s * pitch), 4, "Z") @ Matrix.Rotation(math.radians(-s * 90), 4, "Y")
        m.add(slab_, tex("shingle"), uv_scale=1.0, uv_local=True, transform=t)
    m.add(box((0.7, h + 0.3, 0.2), (1.05, h + 1.6, 0.55), bevel=0.01), tex("brick"), uv_scale=1.0)
    m.add(box((0.67, h + 1.6, 0.17), (1.08, h + 1.66, 0.58), bevel=0.01), matte("6B6466"))
    m.add(box((-0.35, 0, -d / 2 - 0.03), (0.35, 1.35, -d / 2 + 0.01), bevel=0.02), matte(door))
    m.add(box((-0.42, 0, -d / 2 - 0.02), (0.42, 1.42, -d / 2 + 0.01), bevel=0.02), matte(CREAM))
    m.add(sphere((0.22, 0.68, -d / 2 - 0.05), 0.035), matte("C9A040"))
    for x in (-1.05, 1.05):
        m.add(box((x - 0.38, 0.9, -d / 2 - 0.03), (x + 0.38, 1.7, -d / 2 + 0.01), bevel=0.02), matte(CREAM))
        m.add(box((x - 0.3, 0.98, -d / 2 - 0.04), (x + 0.3, 1.62, -d / 2 - 0.02)), glow("FFE2A8") if variant == 1 else glass("9FB9C8"))
        m.add(box((x - 0.015, 0.98, -d / 2 - 0.045), (x + 0.015, 1.62, -d / 2 - 0.035)), matte(CREAM))
        m.add(box((x - 0.3, 1.285, -d / 2 - 0.045), (x + 0.3, 1.315, -d / 2 - 0.035)), matte(CREAM))
        m.add(box((x - 0.45, 0.85, -d / 2 - 0.1), (x + 0.45, 0.92, -d / 2 + 0.02)), matte(CREAM))
    return [m.build()]


