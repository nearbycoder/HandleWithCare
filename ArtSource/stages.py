def catapult():
    """Wooden catapult. Children: Arm (pivot at the axle). Origin at ground level, centred."""
    wood, rope, iron = TIMBER, P("rope", "C9B48A"), P("brushed", "5E6268")
    base = Model("catapult")
    for s in (-1, 1):
        base.add(box((-1.6, 0.0, s * 0.7 - 0.08), (1.6, 0.18, s * 0.7 + 0.08), bevel=0.02), wood)
        base.add(hull([(-0.6, 0.18, s * 0.7 - 0.07), (0.6, 0.18, s * 0.7 - 0.07), (0.0, 1.4, s * 0.7 - 0.07),
                       (-0.6, 0.18, s * 0.7 + 0.07), (0.6, 0.18, s * 0.7 + 0.07), (0.0, 1.4, s * 0.7 + 0.07)], bevel=0.02), wood)
        for x in (-0.45, 0.45):  # iron straps
            base.add(box((x - 0.04, 0.17, s * 0.7 - 0.09), (x + 0.04, 0.2, s * 0.7 + 0.09)), iron)
    for x in (-1.4, 1.4):
        base.add(box((x - 0.08, 0.0, -0.78), (x + 0.08, 0.18, 0.78), bevel=0.02), wood)
    base.add(cyl((0.0, 1.3, 0), 0.08, 1.6, axis="z", segments=20), iron)
    for x in (-1.3, 1.3):
        for z in (-0.78, 0.78):
            base.add(cyl((x, 0.0, z), 0.3, 0.12, axis="z", segments=32, bevel=0.03), wood)
            base.add(torus((x, 0.0, z), 0.3, 0.02, axis="z", segments=32, ring_segments=6), iron)
            base.add(cyl((x, 0.0, z - 0.07 * (1 if z > 0 else -1)), 0.06, 0.04, axis="z", segments=16), iron)
    b = base.build()
    arm = Model("Arm")
    arm.add(box((-0.08, -0.08, -0.12), (2.5, 0.08, 0.12), bevel=0.02), wood)
    arm.add(box((-0.9, -0.3, -0.35), (-0.1, 0.25, 0.35), bevel=0.04), P("matte", "6B6466"))
    for k in range(4):
        arm.add(torus((0.3 + k * 0.4, 0.0, 0.0), 0.1, 0.022, axis="x", segments=16, ring_segments=6), rope)
    a = res(arm.build(origin=(0.0, 1.3, 0), parent=b), 512)
    # the bucket hangs from the arm tip and is kept level in Unity
    bucket = Model("Bucket")
    bucket.add(box((-0.62, -0.06, -0.3), (0.62, 0.0, 0.3), bevel=0.02), wood)
    for sx in (-1, 1):
        bucket.add(box((sx * 0.62 - 0.04, -0.06, -0.3), (sx * 0.62 + 0.04, 0.22, 0.3), bevel=0.02), wood)
    bucket.add(box((-0.62, -0.06, 0.26), (0.62, 0.22, 0.3), bevel=0.02), wood)
    res(bucket.build(origin=(2.5, 1.3, 0), parent=a, parent_origin=(0.0, 1.3, 0)), 512)
    return [b]


