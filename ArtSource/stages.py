def pothole():
    m = Model("prop_pothole")
    rnd = random.Random(3)
    pts = []
    for k in range(24):
        a = k / 24 * 2 * math.pi
        r = 0.42 + rnd.uniform(-0.06, 0.06)
        pts.append((math.cos(a) * r, math.sin(a) * r * 0.85))
    m.add(extrude_outline(pts, -0.02, 0.0, bevel=0.0), P("soil", "2E2A27"), transform=Matrix.Rotation(math.pi / 2, 4, "X"))
    for k in range(14):  # crumbled rim chunks
        a = k / 14 * 2 * math.pi + rnd.uniform(0, 0.3)
        p = V(math.cos(a) * 0.46, 0.004, math.sin(a) * 0.39)
        m.add(displace(ico(p, 0.03 + rnd.uniform(0, 0.03), 2), 0.008, 30, k), P("matte", "4A4644"))
    return [res(m.build(), 512)]


