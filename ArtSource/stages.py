def res(obj, r):
    """Bake resolution for this object (default 1024)."""
    obj["bake_res"] = r
    return obj


def slab(x0, x1, z0, z1, y_bottom, fn, nx, nz):
    """Closed slab whose top surface follows y = fn(x, z) (water, terrain). Smooth shaded."""
    bm = bmesh.new()
    top, bot = [], []
    for i in range(nx + 1):
        rt, rb = [], []
        for j in range(nz + 1):
            x = x0 + (x1 - x0) * i / nx
            z = z0 + (z1 - z0) * j / nz
            rt.append(bm.verts.new((x, fn(x, z), z)))
            rb.append(bm.verts.new((x, y_bottom, z)))
        top.append(rt)
        bot.append(rb)
    for i in range(nx):
        for j in range(nz):
            bm.faces.new((top[i][j], top[i + 1][j], top[i + 1][j + 1], top[i][j + 1]))
            bm.faces.new((bot[i][j], bot[i][j + 1], bot[i + 1][j + 1], bot[i + 1][j]))
    for i in range(nx):
        bm.faces.new((top[i][0], bot[i][0], bot[i + 1][0], top[i + 1][0]))
        bm.faces.new((top[i][nz], top[i + 1][nz], bot[i + 1][nz], bot[i][nz]))
    for j in range(nz):
        bm.faces.new((top[0][j], top[0][j + 1], bot[0][j + 1], bot[0][j]))
        bm.faces.new((top[nx][j], bot[nx][j], bot[nx][j + 1], top[nx][j + 1]))
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    return bm, True


def canopy(m, center, radius, seed, color=None, blobs=11, voxel=0.045, squash=0.8):
    """Leafy crown: overlapping lumpy spheres fused into one mass (leaf detail comes from the bake)."""
    rnd = random.Random(seed)
    parts = []
    c = V(center)
    mat = color or FOLIAGE
    for k in range(blobs):
        d = V(rnd.uniform(-1, 1), rnd.uniform(-0.6, 0.8) * squash, rnd.uniform(-0.8, 0.8))
        if d.length > 1:
            d.normalize()
        p = c + d * radius * 0.65
        r = radius * rnd.uniform(0.3, 0.5)
        parts.append((displace(sphere(p, r, segments=20, rings=14), r * 0.22, 3.0 / r, k + seed), mat))
    m.add_fused(parts, voxel=voxel, smooth_iters=4, smooth_factor=0.5, max_faces=12000)


