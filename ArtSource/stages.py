def robot_arm():
    """Industrial arm in parts: Base (origin at floor), Upper (pivot at shoulder), Fore (pivot at elbow),
    Grip (pivot at wrist). Unity poses the joints."""
    orange, dark, steel = P("enamel", "E07A1F"), P("enamel", "34312F"), P("brushed", "C9CED4")
    base = Model("arm_base")
    base.add(cyl((0, 0.06, 0), 0.4, 0.12, axis="y", segments=40, bevel=0.02), dark)
    for k in range(8):
        a = k / 8 * 2 * math.pi
