    up = Model("Upper")
    up.add(box((-0.11, 0.0, -0.11), (0.11, 1.1, 0.11), bevel=0.06, segments=4), orange)
    up.add(cyl((0, 1.1, 0), 0.14, 0.3, axis="z", segments=32, bevel=0.02), dark)
    up.add(sweep(bezier(V(0.11, 0.1, -0.06), V(0.2, 0.4, -0.06), V(0.2, 0.8, -0.06), V(0.11, 1.0, -0.06), 10), 0.018), RUBBER)
