def rack():
    m = Model("prop_rack")
    blue, beam = P("enamel", "2F5F8F"), P("enamel", "E07B1E")
    rnd = random.Random(7)
    for x in (-1.4, 1.4):
        for z in (-0.4, 0.4):
            m.add(box((x - 0.05, 0, z - 0.05), (x + 0.05, 3.2, z + 0.05), bevel=0.006), blue)
        for y in (0.6, 1.6, 2.6):  # cross bracing
            m.add(rod((x, y - 0.4, -0.4), (x, y + 0.4, 0.4), 0.012), blue)
    for y in (0.3, 1.3, 2.3):
        m.add(box((-1.45, y, -0.45), (1.45, y + 0.08, 0.45), bevel=0.008), beam)
        x = -1.3
